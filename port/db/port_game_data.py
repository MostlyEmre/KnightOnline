#!/usr/bin/env python3
"""Writes the port's additions to the game database as a SQL script that can run again safely.

The 1.298 client sells Low and Middle Class upgrade scrolls at Charon, but OpenKO-db has neither the
scrolls nor anything to tell item classes apart, so the server refuses them. This adds:
- ITEM_GRADE: each upgradeable item's class, as the client works it out for its tooltip ("Item
  Grade": Item_Org byGrade + Item_Ext bySoulBind, capped at 3). Ebenezer reads it to let Low Class
  scrolls take only low class items, and Middle Class ones middle and low.
- The 30 scrolls in ITEM, each a copy of its High Class counterpart with the client's name and price.
- Their ITEM_UPGRADE recipes: copies of the counterpart's, nIndex + 5000 (Low) or + 6000 (Middle),
  which keeps each in its 100000 band and clear of every other recipe.

KnightOnline.app's ko-servers runs the script on the player's database at every start, so new
games and existing saves both get it. The seed itself stays a plain OpenKO-db conversion.

usage: port_game_data.py <client Data dir (assets/Client/Data)> <out.sql>
"""

import csv
import os
import sys

# (High Class, Low Class, Middle Class) scroll item IDs, matched by the client's names.
SCROLL_PAIRS = [
    (379016000, 379221000, 379205000),  # Upgrade Scroll
    (379017000, 379222000, 379206000),  # Enchant Scroll(STR)
    (379026000, 379223000, 379208000),  # Enchant Scroll(HP)
    (379027000, 379224000, 379209000),  # Enchant Scroll(DEX)
    (379028000, 379225000, 379210000),  # Enchant Scroll(INT)
    (379029000, 379226000, 379211000),  # Enchant Scroll(MAGIC)
    (379018000, 379227000, 379212000),  # Immune Scroll
    (379019000, 379228000, 379213000),  # Reduce Scroll
    (379020000, 379229000, 379214000),  # Elemental Scroll
    (379034000, 379230000, 379215000),  # Dispell Scroll(Fire)
    (379035000, 379231000, 379216000),  # Dispell Scroll(Glacier)
    (379138000, 379232000, 379217000),  # Dispell Scroll(Light)
    (379139000, 379233000, 379218000),  # Dispell Scroll(Glacier)
    (379140000, 379234000, 379219000),  # Dispell Scroll(Fire)
    (379141000, 379235000, 379220000),  # Dispell Scroll(Light)
]

LOW_INDEX_OFFSET = 5000
MIDDLE_INDEX_OFFSET = 6000

ITEM_ATTRIB_UPGRADE = 5  # Item_Ext byMagicOrRare: an item that's upgraded, which has a class
MAX_ITEM_EXTENSION = 24
REQ_ITEMS = [f"nReqItem{i}" for i in range(1, 9)]


def read_table(path):
    with open(path, newline="", encoding="utf-8", errors="replace") as f:
        rows = list(csv.reader(f))
    return rows[1:]  # the first row names the column types


def client_items(data_dir):
    """Item_Org: item ID -> (name, price)"""
    return {int(r[0]): (r[2], int(r[20])) for r in read_table(os.path.join(data_dir, "Item_Org_us.tbl.csv"))}


def item_grades(data_dir):
    """Item ID -> class (1 low, 2 middle, 3 high), as CUIImageTooltipDlg shows it; classless items are left out"""
    basics = [(int(r[0]), int(r[1]), int(r[36])) for r in read_table(os.path.join(data_dir, "Item_Org_us.tbl.csv"))]

    soul_binds = {}  # ext table -> {ext ID: bySoulBind} for upgrade extensions
    for ext_index in range(MAX_ITEM_EXTENSION):
        path = os.path.join(data_dir, f"Item_Ext_{ext_index}_us.tbl.csv")
        if os.path.exists(path):
            soul_binds[ext_index] = {int(r[0]): int(r[29]) for r in read_table(path) if int(r[7]) == ITEM_ATTRIB_UPGRADE}

    grades = {}
    for item_id, ext_index, grade in basics:
        for ext_id, soul_bind in soul_binds.get(ext_index, {}).items():
            item_grade = min(3, grade + soul_bind)
            if item_grade >= 1:
                grades[item_id + ext_id] = item_grade
    return grades


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def build_sql(data_dir):
    items = client_items(data_dir)
    out = ["-- Generated by port/db/port_game_data.py from the 1.298 client tables. Safe to run again.", ""]

    out.append("CREATE TABLE IF NOT EXISTS [ITEM_GRADE] ([Num] int NOT NULL, [Grade] tinyint NOT NULL, "
               "PRIMARY KEY ([Num])) WITHOUT ROWID;")
    grades = sorted(item_grades(data_dir).items())
    for start in range(0, len(grades), 500):
        values = ",".join(f"({num},{grade})" for num, grade in grades[start:start + 500])
        out.append(f"INSERT OR REPLACE INTO ITEM_GRADE (Num, Grade) VALUES {values};")
    out.append("")

    # The scrolls: a copy of the counterpart's row (whatever columns ITEM has), renamed and repriced.
    out.append("CREATE TEMP TABLE port_item AS SELECT * FROM ITEM WHERE 0;")
    for high, low, middle in SCROLL_PAIRS:
        for scroll in (low, middle):
            if scroll not in items:
                continue  # only what the client has
            name, price = items[scroll]
            out.append(f"INSERT INTO port_item SELECT * FROM ITEM WHERE Num = {high};")
            out.append(f"UPDATE port_item SET Num = {scroll}, strName = {quote(name)}, BuyPrice = {price} WHERE Num = {high};")
    out.append("INSERT OR IGNORE INTO ITEM SELECT * FROM port_item;")
    out.append("DROP TABLE port_item;")
    out.append("")

    # The recipes: the counterpart's, with the scroll swapped.
    columns = ["nIndex", "nNPCNum", "strName", "strNote", "nOriginType", "nOriginItem"] + REQ_ITEMS + [
        "nReqNoah", "bRateType", "nGenRate", "nGiveItem"]
    for high, low, middle in SCROLL_PAIRS:
        for scroll, offset in ((low, LOW_INDEX_OFFSET), (middle, MIDDLE_INDEX_OFFSET)):
            if scroll not in items:
                continue
            select = [f"nIndex + {offset}", "nNPCNum", "strName", "strNote", "nOriginType", "nOriginItem"]
            select += [f"CASE {c} WHEN {high} THEN {scroll} ELSE {c} END" for c in REQ_ITEMS]
            select += ["nReqNoah", "bRateType", "nGenRate", "nGiveItem"]
            out.append(f"INSERT OR IGNORE INTO ITEM_UPGRADE ({', '.join(columns)}) SELECT {', '.join(select)} "
                       f"FROM ITEM_UPGRADE WHERE {high} IN ({', '.join(REQ_ITEMS)});")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2

    sql = build_sql(argv[1])
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write(sql)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
